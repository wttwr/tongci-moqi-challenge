import { integer, sqliteTable, text } from "drizzle-orm/sqlite-core";

export const rooms = sqliteTable("rooms", {
  code: text("code").primaryKey(),
  prompt: text("prompt").notNull(),
  startMode: text("start_mode").notNull().default("topic"),
  maxPlayers: integer("max_players").notNull().default(2),
  players: text("players").notNull().default("[]"),
  spectators: text("spectators").notNull().default("[]"),
  round: integer("round").notNull().default(1),
  matches: integer("matches").notNull().default(0),
  player1Token: text("player1_token").notNull(),
  player1Name: text("player1_name").notNull(),
  player2Token: text("player2_token"),
  player2Name: text("player2_name"),
  player1Word: text("player1_word"),
  player2Word: text("player2_word"),
  player1Ready: integer("player1_ready", { mode: "boolean" }).notNull().default(false),
  player2Ready: integer("player2_ready", { mode: "boolean" }).notNull().default(false),
  player1NextReady: integer("player1_next_ready", { mode: "boolean" }).notNull().default(false),
  player2NextReady: integer("player2_next_ready", { mode: "boolean" }).notNull().default(false),
  history: text("history").notNull().default("[]"),
  timerSeconds: integer("timer_seconds").notNull().default(30),
  deadline: text("deadline"),
  isPaused: integer("is_paused", { mode: "boolean" }).notNull().default(false),
  pausedRemaining: integer("paused_remaining"),
  createdAt: text("created_at").notNull(),
  updatedAt: text("updated_at").notNull(),
});
